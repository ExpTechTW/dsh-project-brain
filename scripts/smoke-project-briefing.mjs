import assert from "node:assert/strict";
import { buildProjectBriefing } from "../src/host/memory/briefing.js";
import { buildInjectionContext } from "../src/host/memory/inject-context.js";

const brain = {
  project: { name: "demo", description: "A plugin", techStack: { backend: "Express", ci: "GitHub Actions" }, entrypoints: ["src/index.js"] },
  architecture: { overview: { purpose: "Persistent project brain" }, keyFiles: [{ path: "src/host/injector.js" }] },
  todos: [{ id: "t1", title: "Fix inject", status: "in_progress", priority: "high" }],
  timeline: [{ eventType: "session_summary", summary: "Locked briefing to match the sidebar.", occurredAt: 2 }],
  memories: [{ id: "m1", type: "decision", status: "active", title: "Session cwd wins", content: "Always resolve path from session cwd.", importance: 0.9, createdAt: 1, updatedAt: 1 }],
};

const b = buildProjectBriefing(brain);
assert.equal(b.purpose, "Persistent project brain");
assert.doesNotMatch(b.purpose, /GitHub Actions|Express|^demo/);
assert.match(b.markdown, /### 這是什麼/);
assert.match(b.markdown, /### 最近做什麼/);
assert.match(b.markdown, /### 從哪改/);
assert.doesNotMatch(b.markdown, /### 現在卡在哪/);
assert.doesNotMatch(b.markdown, /### 最近為什麼/);
assert.match(b.markdown, /Locked briefing to match the sidebar/);
assert.ok(b.startHere.includes("src/index.js"));
assert.equal(b.recentWorkSource, "session_summary");

const objBrain = Object.assign({}, brain, {
  project: Object.assign({}, brain.project, { entrypoints: [{ path: "src/index.js", type: "main" }] }),
});
assert.ok(buildProjectBriefing(objBrain).startHere.includes("src/index.js"));
assert.doesNotMatch(buildProjectBriefing(objBrain).markdown, /\[object Object\]/);

const scriptBrain = Object.assign({}, brain, {
  project: Object.assign({}, brain.project, {
    entrypoints: [
      { path: "npm run build", type: "script" },
      { path: "src/index.js", type: "service" },
    ],
  }),
});
const scriptBrief = buildProjectBriefing(scriptBrain);
assert.ok(scriptBrief.startHere.includes("src/index.js"));
assert.ok(!scriptBrief.startHere.includes("npm run build"));

const inj = buildInjectionContext(brain);
assert.ok(inj.includes(b.markdown));
assert.match(inj, /Session cwd wins/);
assert.match(inj, /### 從哪改/);
assert.doesNotMatch(inj, /### 上次會話/);
assert.match(inj, /### Core 記憶/);

// 注入必須單獨給出活躍待辦：續接靠 TODO，不能只在「記憶約定」裡空口叮囑
assert.match(inj, /### 活躍待辦/);
assert.match(inj, /Fix inject/);
assert.ok(inj.indexOf("### 活躍待辦") > inj.indexOf("### 最近做什麼"), "活躍待辦與最近做什麼分開成段");
const noTodo = buildInjectionContext(Object.assign({}, brain, { todos: [] }));
assert.doesNotMatch(noTodo, /### 活躍待辦/, "沒有活躍待辦就不佔篇幅");
const doneOnly = buildInjectionContext(Object.assign({}, brain, { todos: [{ id: "t9", title: "已完成項", status: "done" }] }));
assert.doesNotMatch(doneOnly, /### 活躍待辦/);

// 「這是什麼」不能把掃描器佔位符當專案定位
const placeholder = buildProjectBriefing(Object.assign({}, brain, {
  architecture: null,
  project: Object.assign({}, brain.project, { description: "Auto-generated by dsh-project-brain" }),
}));
assert.equal(placeholder.purpose, "");
assert.doesNotMatch(placeholder.markdown, /Auto-generated by dsh-project-brain/);

// 「最近做什麼」必須帶時間，過舊要標註
const freshAt = Date.now() - 3 * 86_400_000;
const fresh = buildProjectBriefing(Object.assign({}, brain, {
  timeline: [{ eventType: "session_summary", summary: "Locked briefing to match the sidebar.", occurredAt: freshAt }],
}));
assert.equal(fresh.recentWorkAt, freshAt);
assert.equal(fresh.recentWorkStale, false);
assert.match(fresh.markdown, /3 天前/);

const oldAt = Date.now() - 90 * 86_400_000;
const old = buildProjectBriefing(Object.assign({}, brain, {
  timeline: [{ eventType: "session_summary", summary: "很久以前的一次續接。", occurredAt: oldAt }],
}));
assert.equal(old.recentWorkStale, true);
assert.match(old.markdown, /可能已過時/);
assert.match(buildInjectionContext(Object.assign({}, brain, {
  timeline: [{ eventType: "session_summary", summary: "很久以前的一次續接。", occurredAt: oldAt }],
})), /可能已過時/);

// todo 兜底沒有時間戳，不能編一個出來
assert.equal(buildProjectBriefing(Object.assign({}, brain, { timeline: [] })).recentWorkAt, 0);

const changelogBrain = Object.assign({}, brain, {
  timeline: [{ eventType: "session_summary", summary: "改了 8 個檔案", occurredAt: 2 }],
});
const b2 = buildProjectBriefing(changelogBrain);
assert.equal(b2.recentWorkSource, "todo");
assert.match(b2.recentWork, /進行中/);
assert.match(b2.recentWork, /Fix inject/);
assert.doesNotMatch(b2.recentWork || "", /改了\s*\d+\s*個檔案/);

const pendingOnly = Object.assign({}, changelogBrain, {
  todos: [{ id: "t2", title: "稍後處理", status: "pending", priority: "low" }],
});
const bPending = buildProjectBriefing(pendingOnly);
assert.equal(bPending.recentWorkSource, "none");
assert.equal(bPending.recentWork, "");

const staleBrain = Object.assign({}, brain, { architectureStale: true });
const b3 = buildProjectBriefing(staleBrain);
assert.equal(b3.stale, true);
assert.ok(!b3.startHere.includes("src/host/injector.js"));
assert.match(b3.markdown, /架構可能過期/);

const noArch = Object.assign({}, brain, { architecture: null });
const b4 = buildProjectBriefing(noArch);
assert.equal(b4.purpose, "A plugin");

const longWhy = "這是一句續接摘要。".repeat(80);
const core15 = [];
for (let i = 0; i < 15; i++) {
  core15.push({
    id: "m" + i,
    type: "decision",
    status: "active",
    title: "CoreFact " + i,
    content: "Standing fact number " + i + " remains true across sessions.",
    importance: 0.8,
    createdAt: i,
    updatedAt: i,
  });
}
const capBrain = Object.assign({}, brain, {
  memories: core15,
  timeline: [{ eventType: "session_summary", summary: longWhy, occurredAt: 9 }],
});
const capInj = buildInjectionContext(capBrain);
for (let i = 0; i < 15; i++) assert.match(capInj, new RegExp("CoreFact " + i));

const empty = buildInjectionContext({ project: null });
assert.equal(empty, "");

console.log("smoke-project-briefing: PASS");
